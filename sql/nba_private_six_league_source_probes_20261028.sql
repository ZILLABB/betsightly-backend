CREATE TABLE IF NOT EXISTS nba_research.nba_league_source_probes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 league text NOT NULL CHECK (league IN ('wnba','ncaa_men','ncaa_women',
    'nbl_au','euroleague','eurocup')),
 provider text NOT NULL CHECK (provider IN ('espn_site_candidate','euroleague_v2_candidate')),
 scope_key text NOT NULL CHECK (length(scope_key) BETWEEN 4 AND 8),
 recorded_at timestamptz NOT NULL DEFAULT now(),
 http_status integer NOT NULL CHECK (http_status BETWEEN 100 AND 599),
 events_observed integer NOT NULL CHECK (events_observed BETWEEN 0 AND 1000),
 identity_complete integer NOT NULL CHECK (identity_complete BETWEEN 0 AND events_observed),
 parsed_final_count integer NOT NULL CHECK (parsed_final_count BETWEEN 0 AND identity_complete),
 source_page_complete boolean NOT NULL DEFAULT false,
 commercial_use_cleared boolean NOT NULL DEFAULT false,
 source_probe_only boolean NOT NULL DEFAULT true,
 CONSTRAINT source_probe_research_only CHECK (commercial_use_cleared = false AND source_probe_only = true)
);
CREATE INDEX IF NOT EXISTS nba_league_source_probes_lookup
ON nba_research.nba_league_source_probes(league,recorded_at DESC);
ALTER TABLE nba_research.nba_league_source_probes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE nba_research.nba_league_source_probes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE nba_research.nba_league_source_probes_id_seq FROM PUBLIC, anon, authenticated;